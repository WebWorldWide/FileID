/// Judges CLIP text search hits: a photo is a good match when its score for
/// "a photo of <words>." beats its score for a generic photo by `margin`.
/// A fixed cosine floor fails because some photos score high for every query;
/// the generic baseline cancels that. Values mirror
/// shared/models/clip-search-baseline.json (calibration in DECISIONS.md).
enum SearchStrength {
    static let margin: Float = 0.035
    static let model = "clip-vitb32-openai-v1:126bacbb4038a0820ca6582bd81f58d7892070deab8317b390e37d7632a53471"

    static func prompt(_ words: String) -> String { "a photo of \(words)." }

    @TaskLocal static var encoder: @Sendable (String) -> [Float]? = { text in
        QueryCommands.clipText.isInstalled ? QueryCommands.clipText.embedText(text) : nil
    }

    static var applies: Bool { CLIPEmbeddingSpace.modelID == model }

    /// The vector that ranks and judges a text search: the photo prompt when the
    /// text model can embed it, else the client's vector.
    static func scoringVector(query: String, supplied: [Float]) -> [Float] {
        let words = query.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !words.isEmpty, let vector = encoder(prompt(words)), vector.count == supplied.count else { return supplied }
        return vector
    }

    static func score(_ query: [Float], _ embedding: [Float]) -> (cosine: Float, margin: Float) {
        var cosine: Float = 0
        var base: Float = 0
        for index in 0..<min(query.count, embedding.count, baseline.count) {
            cosine += query[index] * embedding[index]
            base += baseline[index] * embedding[index]
        }
        return (cosine, cosine - base)
    }

    static func isStrong(_ margin: Float) -> Bool { margin >= SearchStrength.margin }

    static func summary(good: Int, weak: Int) -> String {
        let noun = good == 1 ? "match" : "matches"
        switch (good, weak) {
        case (0, 0): return "No matches."
        case (0, _): return "No good matches, \(weak) weaker."
        case (_, 0): return "\(good) good \(noun)."
        default: return "\(good) good \(noun), \(weak) weaker."
        }
    }

    static let similarWords: Set<String> = ["similar", "closest", "nearest", "lookalike", "lookalikes", "resemble", "resembles", "resembling"]

    /// "show the closest photos of a dog" keeps weaker look-alikes.
    static func wantsSimilar(_ text: String) -> Bool {
        !similarWords.isDisjoint(with: text.lowercased().split { !$0.isLetter }.map(String.init))
    }

