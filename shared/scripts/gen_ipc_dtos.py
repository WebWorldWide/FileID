#!/usr/bin/env python3
"""Generate IPC DTO source from shared/ipc-schema/ipc.schema.json.

The schema decides which messages, variants and fields exist and whether each
field is required. shared/ipc-schema/codegen.json adds only what JSON Schema
cannot say for a language: type names for inline objects, numeric widths,
typed enums, derives, and the few fields whose omission rule differs from the
default (for example a bool that is left out of the JSON when false).

Usage:
  gen_ipc_dtos.py            write every generated file
  gen_ipc_dtos.py --check    fail when a committed generated file is stale, or
                             when a hand-written mirror is missing a schema
                             field (or carries one the schema lacks)
  gen_ipc_dtos.py --print rust|csharp|swift   print generated source
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import textwrap
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCHEMA_PATH = ROOT / "shared/ipc-schema/ipc.schema.json"
CONFIG_PATH = ROOT / "shared/ipc-schema/codegen.json"
HEADER = "@generated by shared/scripts/gen_ipc_dtos.py from shared/ipc-schema/ipc.schema.json. Do not edit; run the script."


class GenError(Exception):
    pass


# ─── Schema model ────────────────────────────────────────────────────────────


@dataclass
class Field:
    wire: str
    node: dict
    required: bool

    @property
    def description(self) -> str:
        return self.node.get("description", "")


@dataclass
class Obj:
    key: str
    node: dict
    fields: list[Field]

    @property
    def description(self) -> str:
        return self.node.get("description", "")


@dataclass
class Variant:
    tag: str
    kind: str  # "empty", "object" (body is an object), "wrap" (body is {"_0": value})
    key: str | None  # object key for "object", or the wrapped value's key
    wrapped: dict | None = None  # wrapped value node for "wrap"
    description: str = ""


@dataclass
class Model:
    schema: dict
    objects: dict[str, Obj] = field(default_factory=dict)
    enums: dict[str, list[str]] = field(default_factory=dict)
    commands: list[Variant] = field(default_factory=list)
    events: list[Variant] = field(default_factory=list)

    def ref_target(self, ref: str) -> tuple[str, dict]:
        parts = ref.removeprefix("#/").split("/")
        node = self.schema
        for part in parts:
            node = node[part]
        if parts[0] == "$defs" and parts[1] == "SinglePositional":
            return parts[2], node
        if parts[0] == "$defs" and len(parts) == 2:
            return parts[1], node
        raise GenError(f"unsupported $ref {ref}")


def types_of(node: dict) -> list[str]:
    value = node.get("type")
    if value is None:
        if node.get("enum") and all(isinstance(v, str) for v in node["enum"]):
            return ["string"]
        return []
    return [value] if isinstance(value, str) else list(value)


def non_null_branch(node: dict) -> dict:
    """Unwrap `{"oneOf": [{"type": "null"}, X]}` to X."""
    for keyword in ("oneOf", "anyOf"):
        if keyword in node:
            branches = [b for b in node[keyword] if b.get("type") != "null"]
            if len(branches) != 1:
                raise GenError(f"only nullable single-branch unions are supported: {node}")
            return branches[0]
    return node


def is_nullable(node: dict) -> bool:
    if "null" in types_of(node):
        return True
    return any(b.get("type") == "null" for b in node.get("oneOf", []) + node.get("anyOf", []))


UNIONS = ("CommandPayload", "EventPayload")


def build_model(schema: dict) -> Model:
    model = Model(schema)
    defs = schema["$defs"]

    def visit(key: str, node: dict) -> None:
        node = non_null_branch(node)
        if "$ref" in node:
            name, target = model.ref_target(node["$ref"])
            if name not in model.objects and name not in model.enums:
                visit_named(name, target)
            return
        kinds = types_of(node)
        if "enum" in node and "string" in kinds:
            model.enums.setdefault(key, list(node["enum"]))
        if "object" in kinds and "properties" in node:
            visit_object(key, node)
        if "array" in kinds:
            visit(key + "[]", node.get("items", {}))

    def visit_named(name: str, node: dict) -> None:
        if name in UNIONS or ("string" in types_of(node) and "enum" not in node):
            return
        if "_0" in node.get("properties", {}) and node.get("required") == ["_0"]:
            inner = node["properties"]["_0"]
            if "$ref" in inner:
                visit(name, inner)
            else:
                visit_object(name, inner)
            return
        if "enum" in node:
            model.enums[name] = list(node["enum"])
            return
        visit_object(name, node)

    def visit_object(key: str, node: dict) -> None:
        if key in model.objects:
            return
        required = set(node.get("required", []))
        fields = [Field(wire, prop, wire in required) for wire, prop in node.get("properties", {}).items()]
        model.objects[key] = Obj(key, node, fields)
        for f in fields:
            visit(f"{key}.{f.wire}", f.node)

    for name in ("IPCCommand", "IPCEvent"):
        visit_object(name, defs[name])

    for branch in defs["CommandPayload"]["oneOf"]:
        (tag, body), = branch["properties"].items()
        if body.get("properties"):
            visit_object(f"command.{tag}", body)
            model.commands.append(Variant(tag, "object", f"command.{tag}", description=body.get("description", "")))
        else:
            model.commands.append(Variant(tag, "empty", None, description=body.get("description", "")))

    for branch in defs["EventPayload"]["oneOf"]:
        (tag, body), = branch["properties"].items()
        if "$ref" in body:
            name, target = model.ref_target(body["$ref"])
            inner = target["properties"]["_0"]
            visit_named(name, target)
            wrapped_key = model.ref_target(inner["$ref"])[0] if "$ref" in inner else name
            model.events.append(Variant(tag, "wrap", wrapped_key, inner, target.get("description", "")))
        elif set(body.get("properties", {})) == {"_0"}:
            inner = body["properties"]["_0"]
            if "$ref" in inner:
                visit(f"event.{tag}._0", inner)
                key = model.ref_target(inner["$ref"])[0]
            else:
                key = f"event.{tag}._0"
                visit_object(key, inner)
            model.events.append(Variant(tag, "wrap", key, inner, body.get("description", "")))
        else:
            visit_object(f"event.{tag}", body)
            model.events.append(Variant(tag, "object", f"event.{tag}", description=body.get("description", "")))

    for name, node in defs.items():
        if name in ("CommandPayload", "EventPayload", "SinglePositional") or name in model.objects or name in model.enums:
            continue
        if "enum" in node or ("type" in node and node["type"] == "object"):
            visit_named(name, node)
    return model


def strip_descriptions(node):
    if isinstance(node, dict):
        return {k: strip_descriptions(v) for k, v in node.items() if k not in ("description", "default")}
    if isinstance(node, list):
        return [strip_descriptions(v) for v in node]
    return node


# ─── Naming helpers ──────────────────────────────────────────────────────────


def pascal(name: str) -> str:
    return name[:1].upper() + name[1:]


def snake(wire: str) -> str:
    text = wire.replace("IDs", "Ids").replace("ID", "Id").replace("GB", "Gb").replace("MB", "Mb")
    return re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", text).lower()


def serde_camel(snake_name: str) -> str:
    head, *rest = snake_name.split("_")
    return head + "".join(part[:1].upper() + part[1:] for part in rest)


def doc_lines(text: str, indent: str, prefix: str, width: int = 100) -> list[str]:
    if not text:
        return []
    wrapped = textwrap.wrap(" ".join(text.split()), width=max(40, width - len(indent) - len(prefix) - 1), break_on_hyphens=False)
    return [f"{indent}{prefix} {line}".rstrip() for line in wrapped]


# ─── Rust ────────────────────────────────────────────────────────────────────

RUST_DERIVE_ORDER = ["Debug", "Clone", "Copy", "Default", "PartialEq", "Eq", "Serialize", "Deserialize"]
RUST_MODES = {"required", "option", "option_keep_null", "default", "default_true", "skip_false", "skip_empty"}


class RustGen:
    def __init__(self, model: Model, config: dict):
        self.model = model
        self.config = config
        self.names: dict[str, str] = dict(config.get("names", {}))
        self.enum_names: dict[str, str] = {}
        for rust_name, spec in config.get("enums", {}).items():
            for key in spec["keys"]:
                self.enum_names[key] = rust_name
        self.types: dict[str, dict] = config.get("types", {})
        self.used_overrides: set[tuple[str, str]] = set()

    def object_name(self, key: str) -> str:
        if key in self.names:
            return self.names[key]
        if key.startswith("command.") and key.count(".") == 1:
            return pascal(key.split(".")[1]) + "Payload"
        if key.startswith("event.") and key.endswith("._0"):
            return pascal(key.split(".")[1])
        if key.startswith("event.") and key.count(".") == 1:
            return pascal(key.split(".")[1]) + "Payload"
        if "." in key:
            raise GenError(f"rust: inline object {key} needs a name in codegen.json rust.names")
        return {"IPCCommand": "IpcCommand", "IPCEvent": "IpcEvent"}.get(key, key)

    def value_type(self, key: str, node: dict) -> str:
        node = non_null_branch(node)
        if "$ref" in node:
            name, target = self.model.ref_target(node["$ref"])
            if name in UNIONS:
                return name
            if name in self.model.enums:
                return self.enum_names.get(name, "String")
            if name not in self.model.objects:
                return self.value_type(name, target)
            return self.object_name(name)
        kinds = [k for k in types_of(node) if k != "null"]
        if len(kinds) != 1:
            raise GenError(f"rust: {key} has ambiguous type {kinds}")
        kind = kinds[0]
        if kind == "string":
            if "enum" in node:
                return self.enum_names.get(key, "String")
            return "String"
        if kind == "integer":
            return "i64"
        if kind == "number":
            return "f64"
        if kind == "boolean":
            return "bool"
        if kind == "array":
            return f"Vec<{self.value_type(key + '[]', node.get('items', {}))}>"
        if kind == "object":
            if "properties" not in node:
                raise GenError(f"rust: open object {key} needs a type override")
            return self.object_name(key)
        raise GenError(f"rust: unsupported type {kind} at {key}")

    def struct_groups(self) -> dict[str, list[Obj]]:
        groups: dict[str, list[Obj]] = {}
        for obj in self.model.objects.values():
            groups.setdefault(self.object_name(obj.key), []).append(obj)
        for name, objs in groups.items():
            shapes = {json.dumps(strip_descriptions(o.node), sort_keys=True) for o in objs}
            if len(shapes) > 1:
                raise GenError(f"rust: {name} names objects with different shapes: {[o.key for o in objs]}")
        return groups

    def render_struct(self, name: str, obj: Obj) -> list[str]:
        spec = self.types.get(name, {})
        unknown = set(spec) - {"derive", "deny_unknown_fields", "order", "fields", "hand_written"}
        if unknown:
            raise GenError(f"rust: {name} has unknown config keys {sorted(unknown)}")
        field_specs = spec.get("fields", {})
        wires = [f.wire for f in obj.fields]
        missing = set(field_specs) - set(wires)
        if missing:
            raise GenError(f"rust: {name} config names fields absent from the schema: {sorted(missing)}")
        order = spec.get("order", wires)
        if sorted(order) != sorted(wires):
            raise GenError(f"rust: {name} order {order} is not a permutation of schema fields {wires}")
        by_wire = {f.wire: f for f in obj.fields}

        lines = doc_lines(obj.description, "", "///")
        derives = {"Debug", "Clone", "Serialize", "Deserialize", *spec.get("derive", [])}
        lines.append("#[derive(" + ", ".join(d for d in RUST_DERIVE_ORDER if d in derives) + ")]")
        container = ['rename_all = "camelCase"']
        if spec.get("deny_unknown_fields"):
            container.append("deny_unknown_fields")
        lines.append(f"#[serde({', '.join(container)})]")
        if not obj.fields:
            lines.append(f"pub struct {name} {{}}")
            return lines
        lines.append(f"pub struct {name} {{")
        for wire in order:
            f = by_wire[wire]
            fspec = field_specs.get(wire, {})
            mode = fspec.get("mode", "required" if f.required else "option")
            if mode not in RUST_MODES:
                raise GenError(f"rust: {name}.{wire} has unknown mode {mode}")
            if f.required and mode in ("option", "option_keep_null") and not is_nullable(f.node):
                raise GenError(f"rust: {name}.{wire} is required and not nullable but mode is {mode}")
            base = fspec.get("type") or self.value_type(f"{obj.key}.{wire}", f.node)
            rust_field = fspec.get("name", snake(wire))
            attrs = []
            if serde_camel(rust_field) != wire:
                attrs.append(f'rename = "{wire}"')
            if mode == "option":
                ty = f"Option<{base}>"
                attrs += ["default", 'skip_serializing_if = "Option::is_none"']
            elif mode == "option_keep_null":
                ty = f"Option<{base}>"
                attrs.append("default")
            elif mode == "default":
                ty = base
                attrs.append("default")
            elif mode == "default_true":
                ty = base
                attrs.append('default = "default_true"')
            elif mode == "skip_false":
                ty = base
                attrs += ["default", 'skip_serializing_if = "is_false"']
            elif mode == "skip_empty":
                ty = base
                kind = "Vec" if base.startswith("Vec<") else base
                attrs += ["default", f'skip_serializing_if = "{kind}::is_empty"']
            else:
                ty = base
            lines += doc_lines(f.description, "    ", "///")
            if attrs:
                lines.append(f"    #[serde({', '.join(attrs)})]")
            lines.append(f"    pub {rust_field}: {ty},")
        lines.append("}")
        return lines

    def render_enum(self, name: str, spec: dict) -> list[str]:
        values = None
        for key in spec["keys"]:
            found = self.model.enums.get(key)
            if found is None:
                raise GenError(f"rust: enum {name} key {key} is not a schema string enum")
            if values is not None and found != values:
                raise GenError(f"rust: enum {name} keys disagree: {values} vs {found}")
            values = found
        derives = {"Debug", "Clone", "Serialize", "Deserialize", *spec.get("derive", [])}
        lines = ["#[derive(" + ", ".join(d for d in RUST_DERIVE_ORDER if d in derives) + ")]",
                 '#[serde(rename_all = "camelCase")]',
                 f"pub enum {name} {{"]
        for value in values:
            variant = pascal(value)
            if serde_camel(snake(variant)) != value and variant[:1].lower() + variant[1:] != value:
                raise GenError(f"rust: enum value {value!r} does not round-trip as a camelCase variant")
            if spec.get("default") == value:
                lines.append("    #[default]")
            lines.append(f"    {variant},")
        lines.append("}")
        return lines

    def variant_payload(self, union: str, variant: Variant) -> str:
        overrides = self.config.get("variants", {}).get(f"{union}.{variant.tag}", {})
        if variant.kind == "empty":
            ty = "Empty"
        elif variant.kind == "object":
            ty = self.object_name(variant.key)
        else:
            inner = variant.wrapped
            if "$ref" in inner:
                ty = self.value_type(variant.key, inner)
            else:
                ty = self.object_name(variant.key)
            ty = f"Wrap<{ty}>"
        if overrides.get("box"):
            ty = f"Box<{ty}>"
        return ty

    def render_union(self, name: str, union: str, variants: list[Variant]) -> list[str]:
        lines = ["#[derive(Debug, Clone, Serialize, Deserialize)]", f"pub enum {name} {{"]
        for variant in variants:
            lines += doc_lines(variant.description, "    ", "///")
            lines.append(f'    #[serde(rename = "{variant.tag}")]')
            lines.append(f"    {pascal(variant.tag)}({self.variant_payload(union, variant)}),")
        lines.append("}")
        return lines

    def render(self) -> str:
        body = self.render_union("CommandPayload", "CommandPayload", self.model.commands) + [""]
        body += self.render_union("EventPayload", "EventPayload", self.model.events) + [""]
        out = body
        hand_written = {n for n, s in self.types.items() if s.get("hand_written")}
        for name, objs in self.struct_groups().items():
            if name in hand_written:
                continue
            out += self.render_struct(name, objs[0]) + [""]
        for name, spec in self.config.get("enums", {}).items():
            out += self.render_enum(name, spec) + [""]
        for const, key in self.config.get("consts", {}).items():
            values = self.model.enums.get(key)
            if values is None:
                raise GenError(f"rust: const {const} names unknown enum {key}")
            items = ", ".join(json.dumps(v) for v in values)
            out.append(f"pub const {const}: [&str; {len(values)}] = [{items}];")
        text = "\n".join(out)
        defined = set(re.findall(r"^pub (?:struct|enum) (\w+)", text, re.M))
        helpers = sorted(
            name for name in self.config.get("helpers", [])
            if re.search(rf"\b{name}\b", text) and name not in defined
        )
        header = [f"// {HEADER}", "", "use serde::{Deserialize, Serialize};", ""]
        if helpers:
            header += [f"use super::{{{', '.join(helpers)}}};", ""]
        return ("\n".join(header + out)).rstrip() + "\n"


# ─── Hand-written mirrors (C#, Swift) ────────────────────────────────────────
#
# Languages that are not generated yet are compared field by field with the
# schema: each schema object maps to one mirror type whose wire keys must equal
# the schema's properties, and each union's variant tags must match.


def dotnet_camel(name: str) -> str:
    """System.Text.Json JsonNamingPolicy.CamelCase."""
    chars = list(name)
    for i, ch in enumerate(chars):
        if not ch.isupper():
            break
        if i > 0 and i + 1 < len(chars) and chars[i + 1].islower():
            break
        chars[i] = ch.lower()
    return "".join(chars)


def split_params(text: str) -> list[str]:
    params, depth, current = [], 0, ""
    for ch in text:
        if ch in "<([{":
            depth += 1
        elif ch in ">)]}":
            depth -= 1
        if ch == "," and depth == 0:
            params.append(current)
            current = ""
        else:
            current += ch
    if current.strip():
        params.append(current)
    return params


def strip_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def matching(text: str, start: int, open_ch: str, close_ch: str) -> int:
    depth, i = 1, start
    while depth:
        if text[i] == open_ch:
            depth += 1
        elif text[i] == close_ch:
            depth -= 1
        i += 1
    return i - 1


def parse_csharp(paths: list[Path]):
    """Records -> wire keys; command tag -> record; event tag -> wrapped type."""
    records: dict[str, list[str]] = {}
    commands: dict[str, str] = {}
    events: dict[str, str] = {}
    for path in paths:
        text = strip_comments(path.read_text(encoding="utf-8-sig"))
        for match in re.finditer(r"\brecord\s+(\w+)\s*(\(|;|:)", text):
            name = match.group(1)
            if match.group(2) != "(":
                records[name] = []
                continue
            end = matching(text, match.end(), "(", ")")
            keys = []
            for param in split_params(text[match.end():end]):
                renamed = re.search(r'JsonPropertyName\("([^"]+)"\)', param)
                bare = re.sub(r"\[[^\]]*\]", "", param).split("=")[0].split()
                keys.append(renamed.group(1) if renamed else dotnet_camel(bare[-1]))
            records[name] = keys
        for match in re.finditer(r'"(\w+)" => (?:JsonSerializer\.Deserialize<(\w+)>|Empty<(\w+)>)', text):
            commands[match.group(1)] = match.group(2) or match.group(3)
        for match in re.finditer(r'"(\w+)" => new (\w+)\((?:ReadWrapped<(\w+)>)?', text):
            events[match.group(1)] = match.group(3) or match.group(2)
    return records, commands, events


def parse_swift(paths: list[Path]):
    """Structs -> wire keys; command tag -> labels; event tag -> wrapped type or labels."""
    structs: dict[str, list[str]] = {}
    commands: dict[str, list[str] | str] = {}
    events: dict[str, list[str] | str] = {}
    for path in paths:
        text = strip_comments(path.read_text(encoding="utf-8"))
        for match in re.finditer(r"^( *)public struct (\w+)\b[^{\n]*\{", text, re.M):
            indent, name = match.group(1), match.group(2)
            body = text[match.end():matching(text, match.end(), "{", "}")]
            member = indent + "    "
            stored = [
                prop.group(1)
                for prop in re.finditer(rf"^{member}(?:public |private |internal |fileprivate )?(?:let|var) (\w+)\s*:\s*[^{{\n]+$", body, re.M)
            ]
            coding = re.search(r"enum CodingKeys\s*:\s*String,\s*CodingKey\s*\{(.*?)\}", body, re.S)
            if coding:
                keys = []
                for case in re.finditer(r"case ([^\n]+)", coding.group(1)):
                    for item in case.group(1).split(","):
                        raw = re.match(r'\s*(\w+)\s*(?:=\s*"([^"]+)")?', item)
                        keys.append(raw.group(2) or raw.group(1))
                stored = keys
            structs[name] = stored
        for envelope, target in (("IPCCommand", commands), ("IPCEvent", events)):
            outer = re.search(rf"public struct {envelope}\b[^{{]*\{{", text)
            if not outer:
                continue
            body = text[outer.end():matching(text, outer.end(), "{", "}")]
            payload = re.search(r"enum Payload\b[^{]*\{", body)
            cases = body[payload.end():matching(body, payload.end(), "{", "}")]
            for case in re.finditer(r"^\s*case (\w+)(?:\((.*)\))?\s*$", cases, re.M):
                tag, params = case.group(1), case.group(2)
                if params is None:
                    target[tag] = []
                    continue
                parts = [p.strip() for p in split_params(params)]
                if all(re.match(r"\w+\s*:", p) for p in parts):
                    target[tag] = [p.split(":")[0].strip() for p in parts]
                else:
                    target[tag] = parts[0]
    return structs, commands, events


def mirror_problems(model: Model, lang: str, spec: dict) -> list[str]:
    paths = [ROOT / p for p in spec["sources"]]
    names: dict[str, str] = spec.get("names", {})
    types, commands, events = (parse_csharp if lang == "csharp" else parse_swift)(paths)
    problems: list[str] = []

    def compare(label: str, schema_keys: list[str], mirror_keys) -> None:
        if mirror_keys is None:
            problems.append(f"{label}: no {lang} type found")
            return
        missing = sorted(set(schema_keys) - set(mirror_keys))
        extra = sorted(set(mirror_keys) - set(schema_keys))
        if missing:
            problems.append(f"{label}: schema fields missing from {lang}: {', '.join(missing)}")
        if extra:
            problems.append(f"{label}: {lang} fields absent from the schema: {', '.join(extra)}")

    for union, variants, mirror in (("CommandPayload", model.commands, commands), ("EventPayload", model.events, events)):
        tags = {v.tag for v in variants}
        for tag in sorted(set(mirror) - tags):
            problems.append(f"{union}.{tag}: {lang} variant absent from the schema")
        for variant in variants:
            label = f"{union}.{variant.tag}"
            if variant.tag not in mirror:
                problems.append(f"{label}: schema variant missing from {lang}")
                continue
            found = mirror[variant.tag]
            if variant.kind == "wrap":
                expected = names.get(variant.key, variant.key)
                if found != expected:
                    problems.append(f"{label}: {lang} carries {found}, codegen.json maps it to {expected}")
                continue
            schema_keys = [f.wire for f in model.objects[variant.key].fields] if variant.kind == "object" else []
            if lang == "csharp":
                compare(label, schema_keys, types.get(found))
            else:
                compare(label, schema_keys, found if isinstance(found, list) else None)

    for key, obj in model.objects.items():
        if key.count(".") == 1 and key.startswith(("command.", "event.")) and not key.endswith("._0"):
            continue
        type_name = names.get(key, key)
        compare(f"{key} ({type_name})", [f.wire for f in obj.fields], types.get(type_name))
    known = spec.get("known_drift", {})
    for item in sorted(set(known) - set(problems)):
        problems.append(f"stale codegen.json {lang}.known_drift entry (fixed? remove it): {item}")
    return [p for p in problems if p not in known]


# ─── Driver ──────────────────────────────────────────────────────────────────


def load() -> tuple[Model, dict]:
    schema = json.loads(SCHEMA_PATH.read_text(encoding="utf-8"))
    config = json.loads(CONFIG_PATH.read_text(encoding="utf-8"))
    return build_model(schema), config


def outputs(model: Model, config: dict) -> dict[Path, str]:
    result = {}
    rust = config["rust"]
    result[ROOT / rust["output"]] = RustGen(model, rust).render()
    return result


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail when generated files are stale")
    parser.add_argument("--mirrors", action="store_true", help="only field-check the hand-written C# and Swift mirrors")
    parser.add_argument("--print", dest="print_lang", choices=["rust"])
    args = parser.parse_args(argv)
    try:
        model, config = load()
        files = outputs(model, config)
    except GenError as error:
        print(f"gen_ipc_dtos: {error}", file=sys.stderr)
        return 1
    if args.print_lang:
        path = ROOT / config[args.print_lang]["output"]
        sys.stdout.write(files[path])
        return 0
    if args.check or args.mirrors:
        failed = False
        if args.check:
            for path, text in files.items():
                if not path.exists() or path.read_text(encoding="utf-8") != text:
                    failed = True
                    print(f"IPC DTO drift: {path.relative_to(ROOT)} is stale; run python3 shared/scripts/gen_ipc_dtos.py", file=sys.stderr)
        for lang in ("csharp", "swift"):
            for problem in mirror_problems(model, lang, config[lang]):
                failed = True
                print(f"IPC DTO drift ({lang}): {problem}", file=sys.stderr)
        if failed:
            return 1
        print("IPC DTOs match ipc.schema.json (Rust generated; C# and Swift mirrors field-checked)")
        return 0
    for path, text in files.items():
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
