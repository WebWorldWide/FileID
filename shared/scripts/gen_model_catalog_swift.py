#!/usr/bin/env python3
"""Embed the Mac MLX model catalog in FileIDModelInfo.

The Rust engine compiles model-catalog.json in (include_str!); this gives the
Swift side the same bytes, so the app, the Swift engine and FileIDAppleKit read
the same catalog in every layout, with or without the resource bundle beside
them (an engine copied alone, as CI runs it).

Usage:
  gen_model_catalog_swift.py          write ModelCatalogData.swift
  gen_model_catalog_swift.py --check  fail when the committed file is stale
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CATALOG_PATH = ROOT / "platforms/apple/shared/Sources/FileIDModelInfo/Resources/model-catalog.json"
OUTPUT_PATH = ROOT / "platforms/apple/shared/Sources/FileIDModelInfo/ModelCatalogData.swift"
HEADER = ("// @generated by shared/scripts/gen_model_catalog_swift.py from Resources/model-catalog.json. "
          "Do not edit; run the script.")


def render(catalog: str) -> str:
    body = catalog[:-1] if catalog.endswith("\n") else catalog
    if '"""#' in body or "\\#" in body or "\r" in body:
        raise ValueError("model-catalog.json contains a sequence a raw Swift string can't hold")
    return (f"{HEADER}\n\n"
            "/// The bytes of model-catalog.json (the catalog the Rust engine embeds too).\n"
            "enum ModelCatalogData {\n"
            "    static let json = #\"\"\"\n"
            f"{body}\n"
            "\"\"\"#\n"
            "}\n")


def main() -> int:
    expected = render(CATALOG_PATH.read_text(encoding="utf-8"))
    if sys.argv[1:] == ["--check"]:
        current = OUTPUT_PATH.read_text(encoding="utf-8") if OUTPUT_PATH.exists() else ""
        if current != expected:
            print(f"{OUTPUT_PATH.relative_to(ROOT)} is stale; run shared/scripts/gen_model_catalog_swift.py", file=sys.stderr)
            return 1
        print(f"{OUTPUT_PATH.relative_to(ROOT)} matches {CATALOG_PATH.relative_to(ROOT)}")
        return 0
    if sys.argv[1:]:
        print(__doc__, file=sys.stderr)
        return 2
    OUTPUT_PATH.write_text(expected, encoding="utf-8")
    print(f"wrote {OUTPUT_PATH.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
