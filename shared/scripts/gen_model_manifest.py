#!/usr/bin/env python3
"""Generate the macOS model table from shared/models/manifest.json.

Usage:
  gen_model_manifest.py          write ModelManifest.swift
  gen_model_manifest.py --check  fail when the committed file is stale
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MANIFEST_PATH = ROOT / "shared/models/manifest.json"
OUTPUT_PATH = ROOT / "platforms/apple/shared/Sources/FileIDShared/ModelManifest.swift"
HEADER = "// @generated by shared/scripts/gen_model_manifest.py from shared/models/manifest.json. Do not edit; run the script."


def literal(value: str) -> str:
    if any(character in value for character in '"\\\n\r') or "\\(" in value:
        raise ValueError(f"unsupported character in manifest string {value!r}")
    return f'"{value}"'


def number(value: int) -> str:
    if not isinstance(value, int) or isinstance(value, bool) or value <= 0:
        raise ValueError(f"approxBytes must be a positive integer; got {value!r}")
    digits = str(value)
    groups = []
    while digits:
        groups.insert(0, digits[-3:])
        digits = digits[:-3]
    return "_".join(groups)


def artifact_url(artifact: dict) -> str:
    return f"https://huggingface.co/{artifact['repo']}/resolve/{artifact['revision']}/{artifact['path']}"


def generate(manifest: dict) -> str:
    policies = manifest["licensePolicies"]
    artifacts = [a for a in manifest["artifacts"] if "macos" in a["platforms"]]
    repos = [r for r in manifest["vlmRepos"] if "macos" in r["platforms"]]
    lines = [
        HEADER,
        "import Foundation",
        "",
        "public struct ModelArtifact: Sendable, Equatable {",
        "    public let id: String",
        "    public let kind: String",
        "    public let url: String",
        "    public let sha256: String",
        "    public let approxBytes: Int64",
        "    public let license: String",
        "}",
        "",
        "public struct VLMRepoPin: Sendable, Equatable {",
        "    public let repo: String",
        "    public let kind: String",
        "    public let revision: String",
        "    public let approxBytes: Int64",
        "    public let license: String",
        "}",
        "",
        "public struct ModelLicensePolicy: Sendable, Equatable {",
        "    public let spdx: String",
        "    public let licenseURL: String",
        "    public let termsRequired: Bool",
        "    public let reviewedAt: String",
        "}",
        "",
        "public enum ModelManifest {",
        "",
        "    public static let licensePolicies: [String: ModelLicensePolicy] = [",
    ]
    for key in sorted(policies):
        policy = policies[key]
        terms = "true" if policy["termsRequired"] is True else "false"
        lines += [
            f"        {literal(key)}: ModelLicensePolicy(",
            f"            spdx: {literal(policy['spdx'])},",
            f"            licenseURL: {literal(policy['licenseUrl'])},",
            f"            termsRequired: {terms},",
            f"            reviewedAt: {literal(policy['reviewedAt'])}),",
        ]
    lines += ["    ]", "", "    public static let artifacts: [ModelArtifact] = ["]
    for artifact in artifacts:
        lines += [
            "        ModelArtifact(",
            f"            id: {literal(artifact['id'])},",
            f"            kind: {literal(artifact['kind'])},",
            f"            url: {literal(artifact_url(artifact))},",
            f"            sha256: {literal(artifact['sha256'])},",
            f"            approxBytes: {number(artifact['approxBytes'])},",
            f"            license: {literal(artifact['license'])}),",
        ]
    lines += ["    ]", "", "    public static let vlmRepos: [VLMRepoPin] = ["]
    for repo in repos:
        lines += [
            "        VLMRepoPin(",
            f"            repo: {literal(repo['repo'])},",
            f"            kind: {literal(repo['kind'])},",
            f"            revision: {literal(repo['revision'])},",
            f"            approxBytes: {number(repo['approxBytes'])},",
            f"            license: {literal(repo['license'])}),",
        ]
    lines += [
        "    ]",
        "",
        "    public static func artifact(id: String) -> ModelArtifact? {",
        "        artifacts.first { $0.id == id }",
        "    }",
        "",
        "    public static func sha256(forURL url: URL) -> String? {",
        "        artifacts.first { $0.url == url.absoluteString }?.sha256",
        "    }",
        "",
        "    public static func vlmPin(forKind kind: String) -> VLMRepoPin? {",
        "        vlmRepos.first { $0.kind == kind }",
        "    }",
        "",
        "    public static func vlmPin(forRepo repo: String) -> VLMRepoPin? {",
        "        if let pin = vlmRepos.first(where: { $0.repo == repo }) { return pin }",
        "        guard let entry = MLXModelCatalog.entry(forRepo: repo) else { return nil }",
        "        return VLMRepoPin(repo: entry.repo, kind: entry.id, revision: entry.revision,",
        "                          approxBytes: entry.weightBytes, license: entry.license)",
        "    }",
        "}",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail when the generated file is stale")
    args = parser.parse_args(argv)
    try:
        text = generate(json.loads(MANIFEST_PATH.read_text(encoding="utf-8")))
    except (OSError, ValueError, KeyError, TypeError) as error:
        print(f"gen_model_manifest: {error}", file=sys.stderr)
        return 1
    relative = OUTPUT_PATH.relative_to(ROOT)
    if args.check:
        if not OUTPUT_PATH.exists() or OUTPUT_PATH.read_text(encoding="utf-8") != text:
            print(f"Model manifest drift: {relative} is stale; run python3 shared/scripts/gen_model_manifest.py", file=sys.stderr)
            return 1
        print(f"{relative} matches shared/models/manifest.json")
        return 0
    OUTPUT_PATH.write_text(text, encoding="utf-8")
    print(f"wrote {relative}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
